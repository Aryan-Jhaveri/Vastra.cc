import { describe, it, expect, vi } from 'vitest'
import { quietHostedKeyHooks } from '../../../helpers/quietHostedHooks.js'
import request from 'supertest'
import { existsSync, rmSync } from 'fs'
import { join } from 'path'
import { nanoid } from 'nanoid'

// Keep the hosted run's OpenRouter key mint/revoke off the network.
quietHostedKeyHooks()

import { app } from '../../../../src/transport/web/server.js'
import { createUser, createSession } from '../../../../src/db/queries.js'
import { createShareInboxPayload, getSharePayload } from '../../../../src/tools/share.js'
