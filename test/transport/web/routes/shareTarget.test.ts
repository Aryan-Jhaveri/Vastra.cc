import { eq } from 'drizzle-orm'

// Valid 1x1 PNG (generated by sharp) — must decode cleanly: sharp >=0.35 fails
// on libpng warnings, so a hand-copied PNG with a bad IDAT CRC is rejected.
const PNG_1x1 = Buffer.from(
  'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAIAAACQd1PeAAAACXBIWXMAAAPoAAAD6AG1e1JrAAAADElEQVQImWP4//8/AAX+Av5Y8msOAAAAAElFTkSuQmCC',
  'base64',
)

function makeUser() {
  const user = createUser(`share-${nanoid(8)}@test.com`, 'hash', 'Sharer')
  const session = createSession(user.id)
  return { id: user.id, token: session.token }
}

const auth = (token: string) => (req: request.Test) =>
  req.set('Authorization', `Bearer ${token}`).set('Cookie', `closet-auth=${token}`)

// The share-target limiter buckets anonymous callers per IP (server sets
// `trust proxy` to 1, so X-Forwarded-For is authoritative for req.ip). Each
// anonymous test below uses its own TEST-NET-3 address so no test can drain
// another's bucket, whatever the order the runner picks (#301) — only the
// rate-limit test deliberately exhausts its own.
function anonPost(ip: string): request.Test {
  return request(app).post('/share-target').set('X-Forwarded-For', ip)
}

// Parse the redirect Location into its query params, transparently unwrapping the
// anonymous `/login?next=<encoded path>` form.
function parseLocation(location: string): { share: string | null; kind: string | null; claim: string | null } {
  const outer = new URL(location, 'http://h')
  const next = outer.searchParams.get('next')
  const target = next ? new URL(next, 'http://h') : outer
  return {
    share: target.searchParams.get('share'),
    kind: target.searchParams.get('kind'),
    claim: target.searchParams.get('claim'),
  }
}

function cleanupUserDir(userId: string) {
  rmSync(join(DATA_DIR, 'users', userId), { recursive: true, force: true })
}

describe('POST /share-target', () => {
  it('authed: 303 → /?share=<id>&kind=inbox, row owned by the session user', async () => {
    const user = makeUser()
    const res = await auth(user.token)(request(app).post('/share-target'))
      .attach('image', PNG_1x1, 'shared.png')

    expect(res.status).toBe(303)
    const { share, kind, claim } = parseLocation(res.headers.location)
    expect(kind).toBe('inbox')
    expect(claim).toBeNull()
    expect(share).toBeTruthy()

    const row = getSharePayload(share!)
    expect(row).toBeDefined()
    expect(row!.userId).toBe(user.id)
    expect(row!.source).toBe('share_inbox')
    expect(row!.claimToken).toBeNull()
    expect(JSON.parse(row!.imageUris)).toHaveLength(1)

    cleanupUserDir(user.id)
  })

  it('anonymous: 303 → /login?next=...&claim=<token>, row owned by __anon__ with a 15-min TTL', async () => {
    const res = await anonPost('203.0.113.1').attach('image', PNG_1x1, 'shared.png')

    expect(res.status).toBe(303)
    expect(res.headers.location.startsWith('/login?next=')).toBe(true)
    const { share, kind, claim } = parseLocation(res.headers.location)
    expect(kind).toBe('inbox')
    expect(share).toBeTruthy()
    expect(claim).toBeTruthy()

    const row = getSharePayload(share!)
    expect(row).toBeDefined()
    expect(row!.userId).toBe('__anon__')
    expect(row!.claimToken).toBe(claim)
    expect(row!.claimToken!.length).toBeGreaterThan(0)
    // ~15 minutes, allow a 5s window for clock drift across the request.
    expect(Math.abs((row!.expiresAt! - row!.createdAt) - 15 * 60 * 1000)).toBeLessThan(5000)
  })

  it('wrong MIME → 400', async () => {
    const res = await anonPost('203.0.113.2').attach('image', Buffer.from('not an image'), 'note.txt')
    expect(res.status).toBe(400)
  })

  it('no file → 400', async () => {
    const res = await anonPost('203.0.113.3').field('text', 'hello')
    expect(res.status).toBe(400)
  })
})

describe('GET /api/share/:id — cross-user isolation (no regression)', () => {
  it('any authenticated user can read a share by id', async () => {
    const userA = makeUser()
    const userB = makeUser()

    const create = await auth(userA.token)(request(app).post('/share-target'))
      .attach('image', PNG_1x1, 'shared.png')
    const { share } = parseLocation(create.headers.location)

    const res = await auth(userB.token)(request(app).get(`/api/share/${share}`))
    expect(res.status).toBe(200)
    expect(res.body.imageUris).toHaveLength(1)

    cleanupUserDir(userA.id)
  })
})

describe('POST /api/share/:id/claim', () => {
  it('happy path: anon row adopted by the claimer, file moved into their tree', async () => {
    const userA = makeUser()

    const create = await anonPost('203.0.113.4').attach('image', PNG_1x1, 'shared.png')
    const { share, claim } = parseLocation(create.headers.location)

    const before = getSharePayload(share!)!
    const uri = JSON.parse(before.imageUris)[0] as string
    expect(existsSync(join(DATA_DIR, 'users', '__anon__', uri))).toBe(true)

    const res = await auth(userA.token)(request(app).post(`/api/share/${share}/claim`)).send({ claimToken: claim })

    expect(res.status).toBe(200)
    expect(res.body.redirect).toBe(`/?share=${share}&kind=inbox`)

    const row = getSharePayload(share!)!
    expect(row.userId).toBe(userA.id)
    expect(row.claimToken).toBeNull()
    // imageUris is unchanged — only ownership flips and the bytes move.
    expect(JSON.parse(row.imageUris)[0]).toBe(uri)

    expect(existsSync(join(DATA_DIR, 'users', userA.id, uri))).toBe(true)
    expect(existsSync(join(DATA_DIR, 'users', '__anon__', uri))).toBe(false)

    cleanupUserDir(userA.id)
    cleanupUserDir('__anon__')
  })

  it('wrong token → 404, row untouched', async () => {
    const userA = makeUser()

    const create = await anonPost('203.0.113.5').attach('image', PNG_1x1, 'shared.png')
    const { share, claim } = parseLocation(create.headers.location)

    const res = await auth(userA.token)(request(app).post(`/api/share/${share}/claim`)).send({ claimToken: 'wrong-token' })
    expect(res.status).toBe(404)

    const row = getSharePayload(share!)!
    expect(row.userId).toBe('__anon__')
    expect(row.claimToken).toBe(claim)

    cleanupUserDir('__anon__')
  })

  it('concurrent claims: exactly one user wins, the other gets 404', async () => {
    const userA = makeUser()
    const userB = makeUser()

    const create = await anonPost('203.0.113.6').attach('image', PNG_1x1, 'shared.png')
    const { share, claim } = parseLocation(create.headers.location)

    const [resA, resB] = await Promise.all([
      auth(userA.token)(request(app).post(`/api/share/${share}/claim`)).send({ claimToken: claim }),
      auth(userB.token)(request(app).post(`/api/share/${share}/claim`)).send({ claimToken: claim }),
    ])

    expect([resA.status, resB.status].sort()).toEqual([200, 404])
    const winner = resA.status === 200 ? userA.id : userB.id
    expect(getSharePayload(share!)!.userId).toBe(winner)

    cleanupUserDir(userA.id)
    cleanupUserDir(userB.id)
    cleanupUserDir('__anon__')
  })

  it('expired → 410, row untouched', async () => {
    const userA = makeUser()
    const token = nanoid(24)
    const payload = createShareInboxPayload({
      userId: '__anon__',
      imageUri: 'images/share-inbox/expired.jpg',
      expiresAt: Date.now() - 1000,
      claimToken: token,
    })

    const res = await auth(userA.token)(request(app).post(`/api/share/${payload.id}/claim`)).send({ claimToken: token })
    expect(res.status).toBe(410)

    const row = getSharePayload(payload.id)!
    expect(row.userId).toBe('__anon__')
    expect(row.claimToken).toBe(token)

    db.delete(sharePayloads).where(eq(sharePayloads.id, payload.id)).run()
  })
})

describe('POST /share-target rate limit', () => {
  it('throttles anonymous callers per IP but not signed-in users', async () => {
    const statuses: number[] = []
    for (let i = 0; i < 15; i++) {
      // No file → 400 while under the limit; the limiter runs before multer.
      const res = await anonPost('203.0.113.7').field('text', 'x')
      statuses.push(res.status)
    }
    expect(statuses).toContain(429)
    expect(statuses.filter(s => s === 400).length).toBeLessThanOrEqual(10)

    // A signed-in user on the same IP has an independent bucket.
    const user = makeUser()
    const res = await auth(user.token)(request(app).post('/share-target')
      .set('X-Forwarded-For', '203.0.113.7').field('text', 'x'))
    expect(res.status).toBe(400)
    cleanupUserDir(user.id)
  })
})
